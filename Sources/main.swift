            if metalRequested && metalFailure == nil {
                do {
                    let renderer = try MetalParticles(frame: v.bounds)
                    renderer.failed = { [weak self, weak renderer] message in
                        guard let self = self, let renderer = renderer,
                              self.views.contains(where: { $0.metal === renderer }) else { return }
                        self.metalFailed(message)
                    }
                    v.wantsLayer = true
                    v.addSubview(renderer.view, positioned: .above, relativeTo: nil)
                    v.metal = renderer
                } catch { metalFailed(error.localizedDescription) }
            }
            p.contentView=v;p.orderFrontRegardless();panels.append(p);views.append(v)
        }
        disabledRects.withUnsafeBufferPointer{snow_disabled_displays($0.baseAddress,Int32($0.count))}
        var rects=screenRects.map{SnowRect(x:$0.minX,y:$0.minY,w:$0.width,h:$0.height)}
        rects.withUnsafeMutableBufferPointer{snow_displays($0.baseAddress,Int32($0.count))}
        previousWindows=[:];motionUntil=0;lastSnapshot=0
