        guard metalFailure == nil else { return }
        metalFailure = message
        NSLog("DesktopSnow Metal fallback to AppKit: %@", message)
        // Keep preference for the next launch; this session falls back on every monitor.
        for v in views { v.metal?.view.removeFromSuperview(); v.metal = nil; v.repaint() }
        if let entry = rendererMenu.items.first(where: { $0.tag == 1 }) {
            entry.title = "Metal (гибрид) · ошибка, сейчас AppKit"
