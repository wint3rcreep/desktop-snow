final class SnowView: NSView {
    weak var controller: SnowController?
    var world = CGRect.zero
    var metal: MetalParticles?
    func repaint() {
        needsDisplay = true
        if let c = controller { metal?.submit(c.sprites, world: world, time: ProcessInfo.processInfo.systemUptime) }
    }
    var lastPointerTimestamp=0.0
    override var isFlipped: Bool { true }
    override var acceptsFirstResponder: Bool { true }
    override func draw(_ dirtyRect: NSRect) {
        NSColor.clear.setFill()
        dirtyRect.fill(using: .copy)
        guard let c = controller else { return }
        let context = NSGraphicsContext.current!.cgContext
        context.saveGState()
        context.translateBy(x: -world.minX, y: -world.minY)
        // Native cubic vector path generated by the SAME C++ geometry as collisions.
        // Explicit run flags prevent joins across windows, gaps and detached bands.
        var bank: CGMutablePath?
        var bankStartX = 0.0
        for curve in c.contours {
            if curve.start != 0 {
                bank = CGMutablePath()
                bankStartX = curve.x0
                bank?.move(to: CGPoint(x:curve.x0,y:curve.y0))
            }
            bank?.addCurve(to:CGPoint(x:curve.x3,y:curve.y3),
                           control1:CGPoint(x:curve.x1,y:curve.y1),
                           control2:CGPoint(x:curve.x2,y:curve.y2))
            if curve.end != 0, let path = bank {
                path.addLine(to:CGPoint(x:bankStartX,y:curve.baseY))
                path.closeSubpath()
                drawVolumetricBank(path, baseY:curve.baseY, context:context)
                bank = nil
            }
        }
        for s in c.sprites {
            if metal != nil && (s.kind == 0 || s.kind == 5) { continue }
            let radius = s.kind == 5 ? s.r * 1.3 : s.r
            let rect = NSRect(x:s.x-radius,y:s.y-radius,width:2*radius,height:2*radius)
            guard world.intersects(rect) else { continue }
            if s.kind == 5 {
                drawLooseSnow(s, context)
            } else if s.kind == 0 {
                NSColor.white.withAlphaComponent(min(1,s.alpha)).setFill()
                NSBezierPath(ovalIn:rect).fill()
                if s.r > 2.3 {
                    NSColor.white.withAlphaComponent(0.12).setFill()
                    NSBezierPath(ovalIn:rect.insetBy(dx:-2,dy:-2)).fill()
                }
            } else {
                let pose = snow_ball_pose(s.x,s.y)
                // Bottom-anchored, area-preserving cosmetic ellipse only.
                // Physics circle and hit testing are never transformed.
                context.saveGState()
                context.translateBy(x:s.x,y:s.y+s.r)
                context.scaleBy(x:1/(1-pose.squash),y:1-pose.squash)
                context.translateBy(x:-s.x,y:-s.y-s.r)
                let gradient = NSGradient(starting: NSColor.white, ending:NSColor(calibratedRed:0.69,green:0.8,blue:0.91,alpha:1))!
                gradient.draw(in:NSBezierPath(ovalIn:rect), angle:70)
                // Rotating specks make rolling visible, not a stationary replacement sprite.
                for i in 0..<4 {
                    let angle = s.angle + pose.tilt + Double(i)*1.57
                    let dot = NSRect(x:s.x+cos(angle)*s.r*0.55-1,y:s.y+sin(angle)*s.r*0.55-1,width:2,height:2)
                    NSColor(calibratedWhite:0.75,alpha:0.5).setFill()
                    NSBezierPath(ovalIn:dot).fill()
                }
                if s.kind == 2 {
                    context.saveGState()
                    context.translateBy(x:s.x,y:s.y)
                    context.rotate(by:pose.tilt)
                    context.translateBy(x:-s.x,y:-s.y)
                    NSColor.black.setFill()
                    for dx in [-0.3,0.3] { NSBezierPath(ovalIn:NSRect(x:s.x+dx*s.r-1.5,y:s.y-s.r*0.25,width:3,height:3)).fill() }
                    let nose=NSBezierPath(); nose.move(to:NSPoint(x:s.x,y:s.y));nose.line(to:NSPoint(x:s.x+s.r*0.8,y:s.y+2));nose.line(to:NSPoint(x:s.x,y:s.y+4));nose.close()
                    NSColor.systemOrange.setFill();nose.fill()
                    let smile=NSBezierPath()
                    smile.move(to:NSPoint(x:s.x-s.r*0.34,y:s.y+s.r*0.28))
                    smile.curve(to:NSPoint(x:s.x+s.r*0.34,y:s.y+s.r*0.28),controlPoint1:NSPoint(x:s.x-s.r*0.17,y:s.y+s.r*0.57),controlPoint2:NSPoint(x:s.x+s.r*0.17,y:s.y+s.r*0.57))
                    smile.lineWidth=max(1,s.r*0.065)
                    NSColor(calibratedRed:0.18,green:0.23,blue:0.29,alpha:1).setStroke();smile.stroke()
                    context.restoreGState()
                }
                context.restoreGState()
            }
        }
        // Original vector artwork; roles come from the live C++ assembly graph.
        // Draw after all balls so the scarf overlaps the neck, not behind the head.
        for s in c.sprites where s.kind == 2 || s.kind == 3 {
            drawAccessories(s)
        }
        for t in c.tractors { drawTractor(t, context) }
        context.restoreGState()
        if c.interactive {
            let text = "DesktopSnow · \(c.sweeping ? "Метла · разбрасывание" : "Катание") · Esc — клики насквозь · авто-выход 60 с"
            text.draw(at:NSPoint(x:24,y:40), withAttributes:[.font:NSFont.systemFont(ofSize:13,weight:.medium),.foregroundColor:NSColor.white,.backgroundColor:NSColor.black.withAlphaComponent(0.7)])
        }
    }
    private func drawVolumetricBank(_ path:CGPath, baseY:Double, context:CGContext) {
        // Independent cached layers, clipped to the SAME supported C1 contour.
        // No outside stroke, blur or rectangular cap can extend beyond support.
        struct Palette {
            static let body = CGGradient(colorsSpace:CGColorSpaceCreateDeviceRGB(), colors:[
                NSColor(calibratedRed:0.95,green:0.98,blue:1,alpha:0.98).cgColor,
                NSColor(calibratedRed:0.71,green:0.82,blue:0.94,alpha:0.98).cgColor
            ] as CFArray, locations:[0,1])!
            static let crown = CGGradient(colorsSpace:CGColorSpaceCreateDeviceRGB(), colors:[
                NSColor.white.withAlphaComponent(0.78).cgColor,
                NSColor.white.withAlphaComponent(0).cgColor
            ] as CFArray, locations:[0,1])!
            static let contact = CGGradient(colorsSpace:CGColorSpaceCreateDeviceRGB(), colors:[
                NSColor(calibratedRed:0.28,green:0.43,blue:0.62,alpha:0).cgColor,
                NSColor(calibratedRed:0.28,green:0.43,blue:0.62,alpha:0.18).cgColor
            ] as CFArray, locations:[0,1])!
        }
        let bounds=path.boundingBoxOfPath
        guard bounds.height > 0 else { return }
        let top=CGPoint(x:bounds.midX,y:bounds.minY)
        let base=CGPoint(x:bounds.midX,y:baseY)
        context.saveGState()
        context.addPath(path)
        context.clip()
        context.drawLinearGradient(Palette.body,start:top,end:base,options:[.drawsBeforeStartLocation,.drawsAfterEndLocation])
        context.drawLinearGradient(Palette.crown,start:top,end:CGPoint(x:bounds.midX,y:bounds.minY+bounds.height*0.72),options:[])
        context.drawLinearGradient(Palette.contact,start:CGPoint(x:bounds.midX,y:baseY-min(3,bounds.height*0.25)),end:base,options:[])
        context.restoreGState()
    }
    // Loose area-carrying grains, not shaded snowman balls. Native point-space
    // vectors are rasterized at the current screen backing scale (including Retina).
    // Fixed translucent skirts avoid per-particle blur/filter/bitmap allocations.
    func drawLooseSnow(_ s:SnowSprite, _ context:CGContext) {
        let r=s.r
        context.saveGState()
        context.setShouldAntialias(true)
        context.translateBy(x:s.x,y:s.y)
        context.rotate(by:s.angle)
        for (scale,alpha) in [(1.28,0.07),(1.12,0.15)] {
            context.setFillColor(NSColor.white.withAlphaComponent(s.alpha*alpha).cgColor)
            context.fillEllipse(in:CGRect(x:-r*scale,y:-r*scale*0.78,width:2*r*scale,height:1.56*r*scale))
        }
        let path=CGMutablePath()
        // A stable asymmetric six-lobed silhouette rotates with the physical grain.
        let lobes=[1.0,0.72,0.91,0.8,1.0,0.76]
        var points:[CGPoint]=[]
        for i in 0..<6 {
            let a=Double(i)*Double.pi/3
            points.append(CGPoint(x:cos(a)*r*lobes[i],y:sin(a)*r*lobes[i]*0.8))
        }
        let first=CGPoint(x:(points[5].x+points[0].x)/2,y:(points[5].y+points[0].y)/2)
        path.move(to:first)
        for i in 0..<6 {
            let next=points[(i+1)%6]
            path.addQuadCurve(to:CGPoint(x:(points[i].x+next.x)/2,y:(points[i].y+next.y)/2),control:points[i])
        }
        path.closeSubpath()
        context.addPath(path)
        context.setFillColor(NSColor(calibratedRed:0.94,green:0.98,blue:1,alpha:s.alpha*0.86).cgColor)
        context.fillPath()
        context.setFillColor(NSColor.white.withAlphaComponent(s.alpha*0.36).cgColor)
        context.fillEllipse(in:CGRect(x:-r*0.52,y:-r*0.5,width:r*0.85,height:r*0.65))
        context.restoreGState()
    }
    // Independent vector snowplow, mirrored to face actual production velocity.
    func drawTractor(_ t:SnowTractor, _ context:CGContext) {
        guard world.contains(CGPoint(x:t.x,y:t.y)) else { return }
        context.saveGState()
        context.translateBy(x:t.x,y:t.y)
        let pose=snow_tractor_pose(t.x,t.y)
        // Shared AppKit actor in both render modes; no wall-clock animation.
        context.translateBy(x:0,y:-pose.lift)
        context.rotate(by:pose.pitch)
        let facing=pose.heading >= 0 ? 1.0 : -1.0
        context.scaleBy(x:facing * max(0.16,abs(pose.heading)),y:1)
        func rounded(_ x:Double,_ y:Double,_ w:Double,_ h:Double,_ radius:Double,_ color:NSColor) {
            color.setFill()
            NSBezierPath(roundedRect:NSRect(x:x,y:y,width:w,height:h),xRadius:radius,yRadius:radius).fill()
        }
        let ink=NSColor(calibratedRed:0.12,green:0.17,blue:0.22,alpha:1)
        let orange=NSColor(calibratedRed:0.94,green:0.52,blue:0.16,alpha:1)
        rounded(-27,-24,51,12,3,ink)
        rounded(-27,-32,49,16,4,orange)
        rounded(-24,-51,27,25,3,ink)
        rounded(-21,-48,21,19,2,orange)
        rounded(-19,-46,16,14,1,NSColor(calibratedRed:0.45,green:0.74,blue:0.83,alpha:1))
        rounded(-12,-46,2,14,0,ink)
        rounded(-19,-46,4,12,1,NSColor.white.withAlphaComponent(0.24))
        rounded(-27,-53,33,4,2,ink)
        rounded(-22,-54,24,2,1,NSColor.white.withAlphaComponent(0.7))
        rounded(10,-42,4,15,1,ink)
        rounded(9,-43,6,3,1,ink)
        rounded(-1,-28,20,2,1,NSColor.white.withAlphaComponent(0.28))
        for x in [-17.0,16.0] {
            NSColor(calibratedWhite:0.08,alpha:1).setFill()
            NSBezierPath(ovalIn:NSRect(x:x-10,y:-20,width:20,height:20)).fill()
            NSColor(calibratedWhite:0.25,alpha:1).setFill()
            NSBezierPath(ovalIn:NSRect(x:x-8,y:-18,width:16,height:16)).fill()
            for index in 0..<8 {
                let angle=t.angle*facing+Double(index)*Double.pi/4
                let tread=NSBezierPath()
                tread.move(to:NSPoint(x:x+cos(angle)*7,y:-10+sin(angle)*7))
                tread.line(to:NSPoint(x:x+cos(angle+0.13)*9,y:-10+sin(angle+0.13)*9))
                tread.lineWidth=1.4;ink.setStroke();tread.stroke()
            }
            NSColor(calibratedWhite:0.72,alpha:1).setFill()
            NSBezierPath(ovalIn:NSRect(x:x-4,y:-14,width:8,height:8)).fill()
            let spoke=NSBezierPath()
            let angle=t.angle*facing
            spoke.move(to:NSPoint(x:x-3*cos(angle),y:-10-3*sin(angle)))
            spoke.line(to:NSPoint(x:x+3*cos(angle),y:-10+3*sin(angle)))
            spoke.lineWidth=1.4;ink.setStroke();spoke.stroke()
        }
        rounded(23,-13,11,4,1,ink)
        let blade=NSBezierPath()
        blade.move(to:NSPoint(x:29,y:-24));blade.line(to:NSPoint(x:36,y:-28))
        blade.line(to:NSPoint(x:38,y:-2));blade.line(to:NSPoint(x:30,y:-2));blade.close()
        NSColor(calibratedRed:0.36,green:0.51,blue:0.62,alpha:1).setFill();blade.fill()
        blade.lineWidth=1;ink.setStroke();blade.stroke()
        rounded(32,-25,2,19,1,NSColor.white.withAlphaComponent(0.35))
        // Bounded silhouette represents existing cargo, not additional physical snow.
        if t.cargo > 0 {
            let h=min(19.0,sqrt(t.cargo)*0.24)
            let mound=NSBezierPath()
            mound.move(to:NSPoint(x:37,y:-1))
            mound.curve(to:NSPoint(x:60,y:-1),controlPoint1:NSPoint(x:38,y:-h*1.8),controlPoint2:NSPoint(x:51,y:-h))
            mound.close();NSColor(calibratedRed:0.83,green:0.91,blue:0.97,alpha:1).setFill();mound.fill()
            let crest=NSBezierPath()
            crest.move(to:NSPoint(x:39,y:-h*0.65))
            crest.curve(to:NSPoint(x:55,y:-h*0.3),controlPoint1:NSPoint(x:44,y:-h*1.1),controlPoint2:NSPoint(x:50,y:-h*0.8))
            crest.lineWidth=1.2;NSColor.white.withAlphaComponent(0.7).setStroke();crest.stroke()
        }
        // Small warm lens and local halo, no shadow/filter or large light cone.
        rounded(19,-30,8,9,2,ink)
        rounded(20,-29,6,7,2,NSColor(calibratedRed:1,green:0.91,blue:0.65,alpha:1))
        rounded(18,-31,10,11,4,NSColor(calibratedRed:1,green:0.89,blue:0.60,alpha:0.08))
        context.restoreGState()
    }
    func drawAccessories(_ s:SnowSprite) {
        let r=s.r, x=s.x, y=s.y
        let pose = snow_ball_pose(s.x,s.y)
        let context=NSGraphicsContext.current!.cgContext
        context.saveGState()
        defer { context.restoreGState() }
        // All decoration remains anchored to a LIVE assembly ball.
        context.translateBy(x:x,y:y)
        context.rotate(by:pose.tilt + pose.flutter*0.15)
        context.translateBy(x:-x,y:-y)
        if s.kind == 2 {
            NSColor(calibratedRed:0.12,green:0.16,blue:0.23,alpha:1).setFill()
            NSBezierPath(roundedRect:NSRect(x:x-r*0.7,y:y-r*2.05,width:r*1.4,height:r*1.12),xRadius:r*0.12,yRadius:r*0.12).fill()
            NSBezierPath(roundedRect:NSRect(x:x-r*1.08,y:y-r*1.04,width:r*2.16,height:r*0.22),xRadius:r*0.1,yRadius:r*0.1).fill()
            NSColor(calibratedRed:0.78,green:0.12,blue:0.19,alpha:1).setFill()
            NSBezierPath(rect:NSRect(x:x-r*0.7,y:y-r*1.23,width:r*1.4,height:r*0.24)).fill()
            NSColor.white.withAlphaComponent(0.10).setFill()
            NSBezierPath(roundedRect:NSRect(x:x-r*0.55,y:y-r*1.95,width:r*0.22,height:r*0.65),xRadius:r*0.06,yRadius:r*0.06).fill()
        } else {
            // Twigs emerge from torso sides, with a fork and a mitten at each tip.
            for side in [-1.0,1.0] {
                let arm=NSBezierPath()
                arm.move(to:NSPoint(x:x+side*r*0.75,y:y-r*0.15))
                arm.line(to:NSPoint(x:x+side*r*1.45,y:y-r*0.5))
                arm.line(to:NSPoint(x:x+side*r*1.85,y:y-r*0.95))
                arm.move(to:NSPoint(x:x+side*r*1.45,y:y-r*0.5))
                arm.line(to:NSPoint(x:x+side*r*1.7,y:y-r*0.32))
                arm.lineWidth=max(2,r*0.12)
                NSColor(calibratedRed:0.35,green:0.21,blue:0.12,alpha:1).setStroke();arm.stroke()
                NSColor(calibratedRed:0.78,green:0.12,blue:0.19,alpha:1).setFill()
                NSBezierPath(ovalIn:NSRect(x:x+side*r*1.85-r*0.24,y:y-r*1.23,width:r*0.48,height:r*0.57)).fill()
                NSBezierPath(ovalIn:NSRect(x:x+side*r*1.65-r*0.14,y:y-r*0.98,width:r*0.28,height:r*0.3)).fill()
            }
            NSColor(calibratedRed:0.78,green:0.12,blue:0.19,alpha:1).setFill()
            NSBezierPath(roundedRect:NSRect(x:x-r*0.72,y:y-r*0.94,width:r*1.44,height:r*0.3),xRadius:r*0.12,yRadius:r*0.12).fill()
            // Tail bends at the sewn neck rather than translating off the body.
            let scarfShade=NSGradient(starting:NSColor(calibratedRed:0.9,green:0.23,blue:0.28,alpha:1),ending:NSColor(calibratedRed:0.48,green:0.05,blue:0.12,alpha:1))!
            context.translateBy(x:x+r*0.37,y:y-r*0.77)
            context.rotate(by:pose.flutter)
            context.translateBy(x:-x-r*0.37,y:-y+r*0.77)
            scarfShade.draw(in:NSBezierPath(roundedRect:NSRect(x:x+r*0.22,y:y-r*0.77,width:r*0.3,height:r*0.95),xRadius:r*0.08,yRadius:r*0.08),angle:0)
        }
    }
    func position(_ event:NSEvent) -> NSPoint {
        let p=convert(event.locationInWindow,from:nil)
        return NSPoint(x:p.x+world.minX,y:p.y+world.minY)
    }
    override func mouseDown(with event:NSEvent) {
        guard let c=controller,c.interactive else{return}
        c.lastInteraction=ProcessInfo.processInfo.systemUptime
        lastPointerTimestamp=event.timestamp
        let p=position(event);snow_down(p.x,p.y,c.sweeping ? 1:0)
    }
    override func mouseDragged(with event:NSEvent) {
        guard let c=controller,c.interactive else{return}
        c.lastInteraction=ProcessInfo.processInfo.systemUptime
        let elapsed=event.timestamp-lastPointerTimestamp
        lastPointerTimestamp=event.timestamp
        let p=position(event);snow_drag_timed(p.x,p.y,c.sweeping ? 1:0,elapsed)
    }
    override func mouseUp(with event:NSEvent) {snow_up()}
    override func keyDown(with event:NSEvent) {
        if event.keyCode == 53 {controller?.setInteractive(false)} else {super.keyDown(with:event)}
    }
}
