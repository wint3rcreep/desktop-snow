    }
    func snapshot(){
        guard let list=CGWindowListCopyWindowInfo([.optionOnScreenOnly,.excludeDesktopElements],kCGNullWindowID) as? [[String:Any]] else {return}
        var result:[SnowWindow]=[];fullScreens=[]
        let myPID=ProcessInfo.processInfo.processIdentifier
        for entry in list {
            guard let pid=entry[kCGWindowOwnerPID as String] as? Int32,pid != myPID,
                  let layer=entry[kCGWindowLayer as String] as? Int,layer==0,
                  let id=entry[kCGWindowNumber as String] as? Int,
                  let dict=entry[kCGWindowBounds as String] as? [String:Any],
                  let x=dict["X"] as? Double,let y=dict["Y"] as? Double,
                  let width=dict["Width"] as? Double,let height=dict["Height"] as? Double,
                  width>70,height>45 else {continue}
            if let alpha=entry[kCGWindowAlpha as String] as? Double,alpha<0.1 {continue}
            let r=CGRect(x:x,y:y,width:width,height:height)
            // Conservative full-display rectangle heuristic, not a private fullscreen API.
            for (i,d) in screenRects.enumerated() where abs(r.minX-d.minX)<3 && abs(r.minY-d.minY)<3 && r.width>=d.width-3 && r.height>=d.height-3 {fullScreens.insert(i)}
            result.append(SnowWindow(id:Int64(id),rect:SnowRect(x:x,y:y,w:width,h:height)))
        }
        let now=ProcessInfo.processInfo.systemUptime
        var current:[Int64:CGRect]=[:]
        for w in result {
            let rect=CGRect(x:w.rect.x,y:w.rect.y,width:w.rect.w,height:w.rect.h)
            current[w.id]=rect
            if let old=previousWindows[w.id],old != rect {motionUntil=now+0.8}
        }
        previousWindows=current
        // Authoritative rectangles feed both collision and rendering. Delayed interpolation
        // would detach snow from the real window; prediction would overshoot on release.
        result.withUnsafeBufferPointer{snow_windows_at($0.baseAddress,Int32($0.count),ProcessInfo.processInfo.systemUptime)}
        let diagnostics=snow_diagnostics()
        trackingItem.title="Рыхлых: \(diagnostics.grains) · сброс: \(diagnostics.bands) · Окон: \(result.count) · \(CGPreflightScreenCaptureAccess() ? "доступ разрешён" : "доступ ограничен")"
        for (i,p) in panels.enumerated(){if hideFullscreen && fullScreens.contains(i){p.orderOut(nil)}else{p.orderFrontRegardless()}}
    }
    func tick(){
        let now=ProcessInfo.processInfo.systemUptime;let delta=min(0.05,max(0,now-last));last=now
        if screenRects.isEmpty {return}
        if interactive && now-lastInteraction>60 {setInteractive(false)}
        let lowPower=ProcessInfo.processInfo.isLowPowerModeEnabled
        let interval=snow_window_interval(lowPower ? 1:0,NSEvent.pressedMouseButtons != 0 ? 1:0,now < motionUntil ? 1:0)
        if now-lastSnapshot >= interval {snapshot();lastSnapshot=now}
        if !paused {snow_step(delta,intensity,wind)}
        // Low power halves paint frequency, not simulation speed.
        if lowPower && Int(now*60)%2==0 {return}
        let ns=spriteBuffer.withUnsafeMutableBufferPointer{snow_sprites($0.baseAddress,Int32($0.count))}
        let np=pileBuffer.withUnsafeMutableBufferPointer{snow_piles($0.baseAddress,Int32($0.count))}
        sprites=Array(spriteBuffer.prefix(Int(ns)));piles=Array(pileBuffer.prefix(Int(np)))
        let required = Int(snow_contours(nil,0))
        var curveBuffer = [SnowCurve](repeating:SnowCurve(),count:required)
        let nc = curveBuffer.withUnsafeMutableBufferPointer { snow_contours($0.baseAddress,Int32($0.count)) }
        contours = Array(curveBuffer.prefix(Int(nc)))
        var tractorBuffer=[SnowTractor](repeating:SnowTractor(),count:screenRects.count)
        let nt=tractorBuffer.withUnsafeMutableBufferPointer{snow_tractors($0.baseAddress,Int32($0.count))}
        tractors=Array(tractorBuffer.prefix(Int(nt)))
        views.forEach{$0.repaint()}
    }
