    @objc func rebuildDisplays(){
        setInteractive(false)
        panels.forEach{$0.close()};panels=[];views=[];screenRects=[];tractors=[]
        guard let primary=NSScreen.screens.first else{return}
        let top=primary.frame.maxY
        var disabledRects:[SnowRect]=[]
        monitorMenu.removeAllItems()
        for (index,s) in NSScreen.screens.enumerated() {
            let key=displayKey(s),enabled = !disabledDisplays.contains(key)
            let label="\(index+1). \(s.localizedName) · \(Int(s.frame.width))×\(Int(s.frame.height))\(s == primary ? " · основной" : "")"
            let entry=item(label,#selector(toggleMonitor(_:)));entry.representedObject=key;entry.state=enabled ? .on:.off;monitorMenu.addItem(entry)
            if !enabled {disabledRects.append(SnowRect(x:s.frame.minX,y:top-s.frame.maxY,w:s.frame.width,h:s.frame.height));continue}
            let f=s.frame
            let world=CGRect(x:f.minX,y:top-f.maxY,width:f.width,height:f.height)
            screenRects.append(world)
            let p=SnowPanel(contentRect:f,styleMask:[.borderless,.nonactivatingPanel],backing:.buffered,defer:false)
            p.isReleasedWhenClosed=false;p.isOpaque=false;p.backgroundColor = .clear;p.hasShadow=false
            p.level = .floating
            p.collectionBehavior=[.canJoinAllSpaces,.fullScreenAuxiliary,.stationary,.ignoresCycle]
            p.hidesOnDeactivate=false;p.ignoresMouseEvents=true;p.isMovable=false
