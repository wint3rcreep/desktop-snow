    func setInteractive(_ enabled:Bool){
        let enabled=enabled && !panels.isEmpty
        interactive=enabled;lastInteraction=ProcessInfo.processInfo.systemUptime;snow_up()
        interactionItem.state=enabled ? .on:.off
        for p in panels {p.ignoresMouseEvents = !enabled}
        if enabled {
            NSApp.activate(ignoringOtherApps:true)
            if let p=panels.first(where:{$0.frame.contains(NSEvent.mouseLocation)}) {p.makeKey();p.makeFirstResponder(p.contentView)}
        } else {for p in panels{p.resignKey()}}
    }
